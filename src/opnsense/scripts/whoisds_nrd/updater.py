def log(message: str) -> None:
    stamp = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")
    print(f"[{stamp}] {message}", flush=True)


def read_run_state() -> dict[str, Any]:
    try:
        loaded = json.loads(RUN_STATE_FILE.read_text(encoding="utf-8"))
        return loaded if isinstance(loaded, dict) else {}
    except (OSError, ValueError):
        return {}


def update_run_state(**updates: Any) -> None:
    """Atomically persist timestamps, archive validation, and dashboard metrics."""
    state = read_run_state()
    state.update(updates)
    RUN_STATE_FILE.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=".run-state.", dir=str(RUN_STATE_FILE.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(state, handle, sort_keys=True, separators=(",", ":"))
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, RUN_STATE_FILE)
    finally:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def file_signature(path: Path) -> dict[str, int]:
    """Cheap local identity for a file; no content read or hash is required."""
    info = path.stat()
    return {
        "size_bytes": int(info.st_size),
        "mtime_ns": int(getattr(info, "st_mtime_ns", int(info.st_mtime * 1_000_000_000))),
        "inode": int(info.st_ino),
    }


# Retain domains parsed during this process so a newly validated archive is not
# parsed a second time when the aggregate is built in the same run.
_LOADED_ARCHIVES: dict[str, tuple[dict[str, int], set[str] | None]] = {}


def cached_archive_validation(path: Path) -> tuple[bool, int] | None:
    """Return cached valid/count metadata when the file stat signature matches."""
    try:
        signature = file_signature(path)
    except OSError:
        return None
    cache = read_run_state().get("archive_validation", {})
    if not isinstance(cache, dict):
        return None
    record = cache.get(path.name)
    if not isinstance(record, dict) or record.get("signature") != signature:
        return None
    try:
        valid = bool(record.get("valid"))
        domain_count = int(record.get("domains", 0))
    except (TypeError, ValueError):
        return None
    return valid, domain_count


def remember_archive_validation(path: Path, domains: set[str] | None) -> None:
    try:
        signature = file_signature(path)
    except OSError:
        return
    valid = domains is not None and len(domains) >= MIN_VALID_DOMAINS
    archive_cache = read_run_state().get("archive_validation", {})
    if not isinstance(archive_cache, dict):
        archive_cache = {}
    archive_cache[path.name] = {
        "signature": signature,
        "valid": valid,
        "domains": len(domains) if valid and domains is not None else 0,
    }
    update_run_state(archive_validation=archive_cache)
    _LOADED_ARCHIVES[str(path)] = (signature, domains if valid else None)


def ensure_directories() -> None:
    # Create only missing directories. Do not chmod or chown pre-existing
    # directories: the operator may already have data or custom permissions.
    if STATE_DIR.is_symlink():
        raise RuntimeError(f"Refusing to use symlink data directory: {STATE_DIR}")
    if STATE_DIR.exists():
        if not STATE_DIR.is_dir():
            raise RuntimeError(f"Data path exists but is not a directory: {STATE_DIR}")
    else:
        STATE_DIR.mkdir(mode=0o700, parents=True, exist_ok=False)

    if DAILY_DIR.is_symlink():
        raise RuntimeError(f"Refusing to use symlink archive directory: {DAILY_DIR}")
    if DAILY_DIR.exists():
        if not DAILY_DIR.is_dir():
            raise RuntimeError(f"Archive path exists but is not a directory: {DAILY_DIR}")
    else:
        DAILY_DIR.mkdir(mode=0o700, exist_ok=False)


def normalize_domain(value: str) -> str | None:
    """Normalize a single FQDN; reject comments, IPs, malformed lines, etc."""
    value = value.strip().strip("\ufeff").rstrip(".").lower()
    if not value or value.startswith(("#", "!", ";")):
        return None
    if any(ch.isspace() for ch in value) or "," in value or "/" in value:
        return None
    try:
        ipaddress.ip_address(value.strip("[]"))
        return None
    except ValueError:
        pass
    try:
        value = value.encode("idna").decode("ascii").lower()
    except UnicodeError:
        return None
    if len(value) > 253 or "." not in value:
        return None
    labels = value.split(".")
    if len(labels) < 2 or any(not label or len(label) > 63 for label in labels):
        return None
    if any(not DOMAIN_LABEL_RE.fullmatch(label) for label in labels):
        return None
    return value


def extract_archive_bytes(payload: bytes) -> bytes:
    """Decode the feed's archive bytes (gzip is used by the upstream script;
    ZIP is also supported because WhoisDS describes the downloads as ZIP files).
    """
    data = payload
    for _ in range(3):
        if data.startswith(b"\x1f\x8b"):
            data = gzip.decompress(data)
            continue
        if data.startswith(b"PK\x03\x04") or zipfile.is_zipfile(BytesIO(data)):
            with zipfile.ZipFile(BytesIO(data)) as zf:
                names = [n for n in zf.namelist() if not n.endswith("/")]
                if not names:
                    raise ValueError("ZIP archive contained no files")
                # Prefer text-like members; otherwise read the first regular member.
                names.sort(key=lambda n: (not n.lower().endswith((".txt", ".list", ".domains")), n))
                parts = [zf.read(name) for name in names]
                data = b"\n".join(parts)
            continue
        # zlib-wrapped DEFLATE is not the normal format, but tolerate it.
        if len(data) > 2 and data[0] == 0x78 and data[1] in (0x01, 0x5E, 0x9C, 0xDA):
            try:
                data = zlib.decompress(data)
                continue
            except zlib.error:
                pass
        break
    return data


def parse_domains(payload: bytes) -> set[str]:
    plain = extract_archive_bytes(payload)
    text = plain.decode("utf-8-sig", errors="replace")
    sample = text[:1000].lower()
    if "<html" in sample or "<!doctype" in sample or "access denied" in sample:
        raise ValueError("download returned HTML/error content instead of a domain list")

    domains: set[str] = set()
    for line in text.splitlines():
        domain = normalize_domain(line)
        if domain:
            domains.add(domain)
    if len(domains) < MIN_VALID_DOMAINS:
        raise ValueError(
            f"only {len(domains):,} valid unique domains found; "
            f"minimum accepted is {MIN_VALID_DOMAINS:,}"
        )
    return domains


def archive_path(day: date) -> Path:
    return DAILY_DIR / f"{day.isoformat()}.txt"


def read_valid_daily_file(path: Path) -> set[str] | None:
    """Read and validate a daily file, reusing the in-process parse when possible."""
    try:
        signature = file_signature(path)
    except OSError:
        return None

    loaded = _LOADED_ARCHIVES.get(str(path))
    if loaded is not None and loaded[0] == signature:
        return loaded[1]

    # A cached invalid result is safe to reuse until the file changes.
    cached = cached_archive_validation(path)
    if cached is not None and not cached[0]:
        _LOADED_ARCHIVES[str(path)] = (signature, None)
        return None

    try:
        data = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    domains = {d for line in data.splitlines() if (d := normalize_domain(line))}
    valid_domains = domains if len(domains) >= MIN_VALID_DOMAINS else None
    remember_archive_validation(path, valid_domains)
    return valid_domains


def archive_is_valid(path: Path) -> bool:
    """Fast existence/validation check; unchanged files are checked with stat only."""
    try:
        file_signature(path)
    except OSError:
        return False
    cached = cached_archive_validation(path)
    if cached is not None:
        return cached[0]
    return read_valid_daily_file(path) is not None


def save_downloaded_archive(path: Path, domains: set[str]) -> None:
    atomic_write_domains(path, domains)
    remember_archive_validation(path, domains)


def make_download_url(day: date) -> str:
    encoded = base64.b64encode(f"{day.isoformat()}.zip".encode("ascii")).decode("ascii")
    return WHOISDS_BASE_URL + urllib.parse.quote(encoded, safe="") + "/nrd"


class ArchiveUnavailable(RuntimeError):
    """The feed does not have this historical date anymore."""


class DownloadFailed(RuntimeError):
    """A network, HTTP, or payload-validation failure occurred."""


def download_day(day: date) -> set[str]:
    url = make_download_url(day)
    request = urllib.request.Request(
        url,
        headers={"User-Agent": USER_AGENT, "Accept": "*/*"},
        method="GET",
    )
    last_error: Exception | None = None
    for attempt in range(1, DOWNLOAD_RETRIES + 2):
        try:
            log(f"Downloading WhoisDS free NRD archive for {day.isoformat()} (attempt {attempt})")
            with urllib.request.urlopen(request, timeout=DOWNLOAD_TIMEOUT_SECONDS) as response:
                status = getattr(response, "status", 200)
                if status != 200:
                    raise RuntimeError(f"HTTP status {status}")
                payload = response.read()
            if not payload:
                raise ValueError("empty download")
            domains = parse_domains(payload)
            log(f"Validated {len(domains):,} unique domains for {day.isoformat()}")
            return domains
        except urllib.error.HTTPError as exc:
            if exc.code in (404, 410):
                raise ArchiveUnavailable(
                    f"WhoisDS no longer has the free archive for {day.isoformat()} (HTTP {exc.code})"
                ) from exc
            last_error = exc
            log(f"Download failed for {day.isoformat()}: HTTP {exc.code}")
            if attempt <= DOWNLOAD_RETRIES:
                time.sleep(3 * attempt)
        except Exception as exc:
            last_error = exc
            log(f"Download/validation failed for {day.isoformat()}: {exc}")
            if attempt <= DOWNLOAD_RETRIES:
                time.sleep(3 * attempt)
    raise DownloadFailed(f"could not retrieve {day.isoformat()}: {last_error}") from last_error


def atomic_write_text(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="ascii", newline="\n") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temp_name, mode)
        os.replace(temp_name, path)
    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise


def atomic_write_domains(
    path: Path,
    domains: Iterable[str],
    *,
    include_subdomain_wildcards: bool = False,
) -> None:
    unique_domains = set(domains)
    entries = set(unique_domains)
    if include_subdomain_wildcards:
        entries.update("*." + domain for domain in unique_domains)
    content = "".join(entry + "\n" for entry in sorted(entries))
    atomic_write_text(path, content, 0o644)


def acquire_lock():
    """Return an open lock file; flock prevents overlapping cron/manual runs."""
    import fcntl

    handle = open(LOCK_FILE, "w")
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        handle.close()
        raise RuntimeError("another WhoisDS NRD update is already running")
    return handle


def prune_old_archives(anchor_day: date, retention_days: int) -> int:
    cutoff = anchor_day - timedelta(days=retention_days - 1)
    removed = 0
    removed_names: set[str] = set()
    for path in DAILY_DIR.iterdir():
        match = DATE_FILE_RE.match(path.name)
        if not match or not path.is_file():
            continue
        try:
            file_day = date.fromisoformat(match.group(1))
        except ValueError:
            continue
        if file_day < cutoff or file_day > anchor_day:
            path.unlink(missing_ok=True)
            removed_names.add(path.name)
            removed += 1
    if removed_names:
        state = read_run_state()
        cache = state.get("archive_validation", {})
        if isinstance(cache, dict):
            for name in removed_names:
                cache.pop(name, None)
            update_run_state(archive_validation=cache)
        for name in removed_names:
            _LOADED_ARCHIVES.pop(str(DAILY_DIR / name), None)
    return removed


def clear_local_store() -> int:
    """Delete only this plugin's date-named archives and atomically empty its feed."""
    removed = 0
    for path in DAILY_DIR.iterdir():
        if DATE_FILE_RE.fullmatch(path.name) and path.is_file():
            path.unlink()
            removed += 1
    atomic_write_domains(OUTPUT_FILE, ())
    _LOADED_ARCHIVES.clear()
    update_run_state(archive_validation={}, aggregate_signature=None, status_snapshot={})
    log(
        f"RESET: removed {removed} daily archive(s) and replaced "
        f"{OUTPUT_FILE} with an empty feed"
    )
    return removed


def _aggregate_input_signature(
    anchor_day: date,
    retention_days: int,
    excluded_tlds: set[str],
    archive_records: list[dict[str, Any]],
) -> str:
    payload = {
        "anchor": anchor_day.isoformat(),
        "retention_days": retention_days,
        "excluded_tlds": sorted(excluded_tlds),
        "archives": archive_records,
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def aggregate_local_archives(
    anchor_day: date,
    retention_days: int,
    excluded_tlds: set[str],
    *,
    allow_empty: bool = False,
) -> tuple[set[str], set[str], int, int, int, bool]:
    """Publish only when daily inputs/settings changed; otherwise use cached metrics."""
    pruned = prune_old_archives(anchor_day, retention_days)
    if pruned:
        log(f"Removed {pruned} daily archive(s) outside the {retention_days}-day window")

    archive_paths: list[Path] = []
    archive_records: list[dict[str, Any]] = []
    days_summary: list[dict[str, Any]] = []
    raw_total = 0
    for path in sorted(DAILY_DIR.glob("????-??-??.txt"), reverse=True):
        if not DATE_FILE_RE.fullmatch(path.name) or not path.is_file():
            continue
        try:
            file_day = date.fromisoformat(path.stem)
            signature = file_signature(path)
        except (ValueError, OSError):
            continue
        cached = cached_archive_validation(path)
        if cached is None:
            domains = read_valid_daily_file(path)
            if domains is None:
                log(f"WARNING: ignoring invalid/undersized local archive {path.name}")
                continue
            domain_count = len(domains)
        else:
            valid, domain_count = cached
            if not valid:
                continue
        archive_paths.append(path)
        archive_records.append({"date": file_day.isoformat(), "signature": signature, "domains": domain_count})
        raw_total += domain_count
        days_summary.append({"date": file_day.isoformat(), "domains": domain_count, "size_bytes": signature["size_bytes"]})

    valid_days = len(archive_paths)
    if not archive_paths and not allow_empty:
        raise RuntimeError("no valid daily NRD archives are available; refusing to replace the output list")

    input_signature = _aggregate_input_signature(anchor_day, retention_days, excluded_tlds, archive_records)
    state = read_run_state()
    snapshot = state.get("status_snapshot") if isinstance(state.get("status_snapshot"), dict) else {}
    try:
        current_output_signature = file_signature(OUTPUT_FILE) if OUTPUT_FILE.is_file() else None
    except OSError:
        current_output_signature = None
    saved_output_signature = state.get("aggregate_output_signature")
    can_skip = (
        pruned == 0
        and OUTPUT_FILE.is_file()
        and state.get("aggregate_signature") == input_signature
        and saved_output_signature == current_output_signature
        and bool(snapshot.get("stats_available"))
    )
    if can_skip:
        log("No daily archive or settings changes detected; skipping aggregate rebuild")
        return set(), set(), valid_days, raw_total, pruned, False

    all_domains: set[str] = set()
    for path in archive_paths:
        domains = read_valid_daily_file(path)
        if domains is None:
            log(f"WARNING: archive changed or became invalid during aggregation: {path.name}")
            continue
        all_domains.update(domains)

    if not all_domains and not allow_empty:
        raise RuntimeError("no valid daily NRD archives are available; refusing to replace the output list")

    published_domains, excluded_count = filter_excluded_tlds(all_domains, excluded_tlds)
    atomic_write_domains(OUTPUT_FILE, published_domains, include_subdomain_wildcards=True)
    output_signature = file_signature(OUTPUT_FILE)
    status_snapshot = {
        "stats_available": True,
        "anchor_date": anchor_day.isoformat(),
        "retention_days": retention_days,
        "excluded_tlds": sorted(excluded_tlds),
        "unique_domains": len(published_domains),
        "raw_daily_entries": raw_total,
        "retained_days": valid_days,
        "excluded_tld_domains": excluded_count,
        "published_entries": len(published_domains) * 2,
        "wildcard_entries": len(published_domains),
        "days": days_summary,
        "output_bytes": output_signature["size_bytes"],
    }
    update_run_state(
        aggregate_signature=input_signature,
        aggregate_output_signature=output_signature,
        status_snapshot=status_snapshot,
        archive_validation=read_run_state().get("archive_validation", {}),
    )
    log(
        f"Generated {OUTPUT_FILE}: {len(published_domains):,} unique apex domains; "
        f"{len(published_domains) * 2:,} published lines including subdomain wildcards; "
        f"{excluded_count:,} domains excluded by TLD/suffix filters; "
        f"{valid_days} daily file(s) ({raw_total:,} per-day unique entries)"
    )
    if valid_days < retention_days:
        log(
            f"NOTE: currently holding {valid_days} valid daily date(s), not {retention_days}. "
            "The initial seed is limited by the free feed's historical availability; "
            "the rolling store will fill as daily runs succeed."
        )
    return all_domains, published_domains, valid_days, raw_total, pruned, True


def update_local_store(no_backfill: bool = False) -> tuple[int, int, int, bool]:
    """Fetch only missing newest dates, fall back one day, and rebuild only on changes."""
    retention_days, excluded_tlds = load_settings()
    update_run_state(last_checked_utc=utc_now_iso())
    requested_day = datetime.now(timezone.utc).date()
    anchor_day: date | None = None
    log(
        f"Checking newest feed date: {requested_day.isoformat()} (UTC); retention: {retention_days} daily dates; "
        f"TLD exclusions: {','.join(sorted(excluded_tlds)) or '(none)'}"
    )

    # Establish an anchor by stat-checking today's archive first. Only a missing,
    # changed, or invalid file is downloaded/parsed. Yesterday is the publication fallback.
    for offset in range(FEED_DATE_FALLBACK_DAYS + 1):
        candidate_day = requested_day - timedelta(days=offset)
        path = archive_path(candidate_day)
        if archive_is_valid(path):
            cached = cached_archive_validation(path)
            count = cached[1] if cached else 0
            log(f"Already have {candidate_day.isoformat()}: {count:,} validated domains; skipping download")
            anchor_day = candidate_day
            break
        try:
            domains = download_day(candidate_day)
            save_downloaded_archive(path, domains)
            log(f"Saved {path} ({len(domains):,} domains)")
            anchor_day = candidate_day
            break
        except (ArchiveUnavailable, DownloadFailed) as exc:
            log(f"WARNING: feed date {candidate_day.isoformat()} is not usable: {exc}")
            if offset < FEED_DATE_FALLBACK_DAYS:
                log(f"Trying previous feed date {(candidate_day - timedelta(days=1)).isoformat()} (UTC)")

    # If today's and yesterday's sources cannot be reached, preserve the newest
    # already validated local date instead of pruning based on an assumed date.
    if anchor_day is None:
        local_dates: list[date] = []
        for path in DAILY_DIR.glob("????-??-??.txt"):
            if DATE_FILE_RE.fullmatch(path.name) and path.is_file():
                try:
                    file_day = date.fromisoformat(path.stem)
                except ValueError:
                    continue
                if file_day < requested_day and archive_is_valid(path):
                    local_dates.append(file_day)
        if local_dates:
            anchor_day = max(local_dates)
            log(f"Using newest previously validated local archive {anchor_day.isoformat()} (UTC)")
        else:
            raise RuntimeError("today's and yesterday's feeds are unavailable and no valid local archive exists")

    dates: list[date] = []
    if not no_backfill:
        backfill_count = min(REMOTE_BACKFILL_DAYS, retention_days)
        dates.extend(anchor_day - timedelta(days=i) for i in range(1, backfill_count))

    for day in dates:
        path = archive_path(day)
        if archive_is_valid(path):
            cached = cached_archive_validation(path)
            count = cached[1] if cached else 0
            log(f"Already have {day.isoformat()}: {count:,} validated domains; skipping download")
            continue
        try:
            domains = download_day(day)
            save_downloaded_archive(path, domains)
            log(f"Saved {path} ({len(domains):,} domains)")
        except ArchiveUnavailable as exc:
            log(f"WARNING: {exc}")
        except DownloadFailed as exc:
            log(f"WARNING: {exc}; stopping historical backfill attempts for this run")
            break
        except Exception as exc:
            log(f"WARNING: leaving {day.isoformat()} absent; {exc}")

    _all, published, valid_days, _raw, pruned, rebuilt = aggregate_local_archives(
        anchor_day, retention_days, excluded_tlds
    )
    snapshot = read_run_state().get("status_snapshot", {})
    published_count = int(snapshot.get("unique_domains", len(published))) if isinstance(snapshot, dict) else len(published)
    excluded_count = int(snapshot.get("excluded_tld_domains", 0)) if isinstance(snapshot, dict) else 0
    log(
        f"Aggregate summary: {published_count:,} unique domains published; "
        f"{excluded_count:,} omitted by TLD filter"
    )
    if not rebuilt:
        log("Aggregate unchanged; Unbound refresh decision will use the recorded ingestion state")
    return published_count, valid_days, pruned, rebuilt


def rebuild_local_store() -> tuple[int, int, int, bool]:
    """Reconcile the aggregate against existing archives/settings; never contact WhoisDS."""
    retention_days, excluded_tlds = load_settings()
    available_days = []
    for path in DAILY_DIR.glob("????-??-??.txt"):
        if DATE_FILE_RE.fullmatch(path.name) and path.is_file() and archive_is_valid(path):
            try:
                available_days.append(date.fromisoformat(path.stem))
            except ValueError:
                pass
    anchor_day = max(available_days) if available_days else datetime.now(timezone.utc).date()
    log(
        f"Rebuilding aggregate from existing archives (anchor: {anchor_day.isoformat()} UTC); retention: {retention_days} days; "
        f"TLD exclusions: {','.join(sorted(excluded_tlds)) or '(none)'}"
    )
    _all, published, valid_days, _raw, pruned, rebuilt = aggregate_local_archives(
        anchor_day, retention_days, excluded_tlds, allow_empty=True
    )
    snapshot = read_run_state().get("status_snapshot", {})
    published_count = int(snapshot.get("unique_domains", len(published))) if isinstance(snapshot, dict) else len(published)
    return published_count, valid_days, pruned, rebuilt


class NRDRequestHandler(http.server.BaseHTTPRequestHandler):
    server_version = "WhoisDS-NRD-Local/1.0"

    def do_GET(self):  # noqa: N802 - BaseHTTPRequestHandler API
        route = urllib.parse.urlsplit(self.path).path
        if route == HTTP_HEALTH_PATH:
            body = HTTP_HEALTH_TOKEN
            content_type = "text/plain; charset=utf-8"
            status = 200
        elif route == HTTP_LIST_PATH:
            try:
                body = OUTPUT_FILE.read_bytes()
            except OSError:
                body = b"NRD list not generated\n"
                status = 503
            else:
                status = 200
            content_type = "text/plain; charset=utf-8"
        else:
            body = b"Not found\n"
            status = 404
            content_type = "text/plain; charset=utf-8"

        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store, max-age=0")
        self.end_headers()
        self.wfile.write(body)

    def do_HEAD(self):  # noqa: N802 - BaseHTTPRequestHandler API
        route = urllib.parse.urlsplit(self.path).path
        if route == HTTP_HEALTH_PATH:
            body = HTTP_HEALTH_TOKEN
            status = 200
        elif route == HTTP_LIST_PATH and OUTPUT_FILE.exists():
            body = b""
            status = 200
        else:
            body = b""
            status = 404
        self.send_response(status)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store, max-age=0")
        self.end_headers()

    def log_message(self, fmt, *args):
        # Keep routine HTTP requests out of the console and firewall logs.
        return


def serve_local_list() -> None:
    if not OUTPUT_FILE.exists():
        raise RuntimeError(f"{OUTPUT_FILE} does not exist; run an update first")
    class LoopbackHTTPServer(http.server.ThreadingHTTPServer):
        daemon_threads = True
        allow_reuse_address = True

    server = LoopbackHTTPServer((HTTP_BIND, HTTP_PORT), NRDRequestHandler)
    log(f"Serving {HTTP_LIST_PATH} on http://{HTTP_BIND}:{HTTP_PORT} (loopback only)")
    try:
        server.serve_forever(poll_interval=0.5)
    finally:
        server.server_close()


def local_server_is_ready() -> bool:
    try:
        with urllib.request.urlopen(
            f"http://{HTTP_BIND}:{HTTP_PORT}{HTTP_HEALTH_PATH}", timeout=2
        ) as response:
            return response.read() == HTTP_HEALTH_TOKEN
    except Exception:
        return False


def ensure_local_server() -> None:
    if not local_server_is_ready():
        raise RuntimeError(
            "WhoisDS NRD HTTP service is not running. Start it with "
            "service whoisds_nrd start before refreshing Unbound."
        )


def unbound_feed_cache_path() -> Path:
    """Return OPNsense's cache path for this plugin's exact URL."""
    digest = hashlib.md5(LOCAL_FEED_URL.encode("utf-8")).hexdigest()
    return UNBOUND_URL_CACHE_DIR / digest


def invalidate_unbound_feed_cache() -> int:
    """Remove only Unbound's cached copy of this plugin's exact feed URL.

    OPNsense 26.7's default blocklist handler hashes the URI with MD5 and
    stores the cache at /tmp/bl_cache/<digest>. Removing only this entry
    forces the next DNSBL update to fetch the changed NRD aggregate, without
    changing the cache TTL or disturbing unrelated blocklists.
    """
    cache_file = unbound_feed_cache_path()
    removed = 0
    for path in (cache_file, Path(str(cache_file) + ".tmp")):
        try:
            path.unlink()
            removed += 1
        except FileNotFoundError:
            pass
    log(
        f"Invalidated {removed} Unbound cache file(s) for the plugin feed "
        f"({LOCAL_FEED_URL})"
    )
    return removed


def _count_file_lines(path: Path) -> int:
    """Count cached feed lines with a bounded-memory binary scan."""
    with path.open("rb") as handle:
        return sum(1 for _line in handle)


def unbound_refresh_required() -> bool:
    """Return true when the current feed has not been ingested or cache is absent."""
    if not OUTPUT_FILE.is_file():
        return False
    current_signature = file_signature(OUTPUT_FILE)
    state = read_run_state()
    if state.get("unbound_ingest_status") != "verified":
        return True
    if state.get("unbound_ingested_output_signature") != current_signature:
        return True
    # /tmp is volatile. A reboot or cleanup removes the cache, so request one
    # fresh ingestion even when the aggregate itself has not changed.
    return not unbound_feed_cache_path().is_file()


def _expected_feed_counts() -> tuple[int, int]:
    state = read_run_state()
    snapshot = state.get("status_snapshot")
    if isinstance(snapshot, dict) and snapshot.get("stats_available"):
        try:
            return int(snapshot.get("published_entries", 0)), int(snapshot.get("wildcard_entries", 0))
        except (TypeError, ValueError):
            pass
    # This fallback is used only for manual refreshes before a status snapshot
    # exists. Normal scheduled updates use the counts recorded during rebuild.
    if not OUTPUT_FILE.exists():
        return 0, 0
    lines = _count_file_lines(OUTPUT_FILE)
    return lines, lines // 2


def refresh_unbound(no_refresh: bool = False, force_fetch: bool = False) -> bool:
    """Refresh DNSBL and verify that Unbound consumed the current NRD feed.

    configctl's OPNsense 26.7 dnsbl action can mask internal script failures
    with ``|| true``. Therefore a zero exit code alone is not proof of success.
    We verify both the URL cache (complete expected line count) and that the
    DNSBL JSON database was atomically replaced by the parser.
    """
    if no_refresh:
        update_run_state(
            unbound_ingest_status="pending",
            unbound_ingest_error="Unbound refresh skipped by --no-refresh",
        )
        log("Skipping Unbound DNSBL refresh (--no-refresh was specified); ingestion remains pending")
        return False
    cache_file = unbound_feed_cache_path()
    try:
        db_before = file_signature(UNBOUND_DNSBL_FILE) if UNBOUND_DNSBL_FILE.is_file() else None
    except OSError:
        db_before = None
    expected_lines, expected_wildcards = _expected_feed_counts()
    attempt_time = utc_now_iso()
    update_run_state(
        last_unbound_refresh_attempt_utc=attempt_time,
        unbound_ingest_status="refreshing",
        unbound_ingest_error=None,
    )

    try:
        if not Path(CONFIGCTL).exists():
            raise RuntimeError(f"{CONFIGCTL} not found; list was generated but Unbound was not refreshed")
        ensure_local_server()
        # Always force a fresh read for calls that represent a pending or
        # changed NRD feed. This only removes this URL's cache entry.
        if force_fetch:
            invalidate_unbound_feed_cache()
        log("Running configctl unbound dnsbl to refresh Unbound DNSBL policies")
        result = subprocess.run(
            [CONFIGCTL, "unbound", "dnsbl"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=1800,
            check=False,
        )
        if result.stdout.strip():
            for line in result.stdout.rstrip().splitlines()[-40:]:
                log("configctl: " + line)
        if result.returncode != 0:
            raise RuntimeError(f"configctl unbound dnsbl exited with status {result.returncode}")

        if not cache_file.is_file():
            raise RuntimeError(
                "Unbound DNSBL command returned, but the NRD URL cache was not created; "
                "check the Unbound resolver log for download errors"
            )
        cached_lines = _count_file_lines(cache_file)
        if cached_lines != expected_lines:
            raise RuntimeError(
                f"Unbound cached {cached_lines:,} NRD lines, expected {expected_lines:,}; "
                "the feed may have been truncated or not fully downloaded"
            )

        try:
            db_after = file_signature(UNBOUND_DNSBL_FILE) if UNBOUND_DNSBL_FILE.is_file() else None
        except OSError:
            db_after = None
        db_replaced = bool(
            db_after
            and (db_before is None or db_after != db_before)
            and UNBOUND_DNSBL_FILE.stat().st_size > 0
        )
        if not db_replaced:
            raise RuntimeError(
                "NRD cache was refreshed, but /var/unbound/data/dnsbl.json was not replaced; "
                "OPNsense may have skipped or failed DNSBL parsing"
            )

        output_signature = file_signature(OUTPUT_FILE) if OUTPUT_FILE.is_file() else None
        cache_signature = file_signature(cache_file)
        completed = utc_now_iso()
        update_run_state(
            last_unbound_refresh_utc=completed,
            last_unbound_ingest_utc=completed,
            unbound_ingest_status="verified",
            unbound_ingest_error=None,
            unbound_ingested_output_signature=output_signature,
            unbound_cache_signature=cache_signature,
        )
        log(
            f"VERIFIED: Unbound fetched {cached_lines:,}/{expected_lines:,} NRD feed lines; "
            f"DNSBL database was regenerated ({UNBOUND_DNSBL_FILE.stat().st_size:,} bytes). "
            f"Expected wildcard entries: {expected_wildcards:,}."
        )
        return True
    except Exception as exc:
        update_run_state(
            unbound_ingest_status="failed",
            unbound_ingest_error=str(exc),
        )
        raise


def main() -> int:
    parser = argparse.ArgumentParser(description="Update WhoisDS NRD rolling blocklist on OPNsense")
    parser.add_argument("--serve", action="store_true", help="run the loopback-only HTTP server")
    parser.add_argument("--clear", action="store_true", help="delete stored daily archives and empty the published feed")
    parser.add_argument("--no-refresh", action="store_true", help="generate the list without refreshing Unbound")
    parser.add_argument("--no-backfill", action="store_true", help="only fetch the latest completed feed date")
    parser.add_argument("--rebuild", action="store_true", help="rebuild from existing archives using saved settings; do not download")
    parser.add_argument("--refresh-unbound", action="store_true", help="force-refresh only this feed in Unbound DNSBL and verify ingestion")
    args = parser.parse_args()

    require_python313()
    ensure_directories()
    if args.serve:
        serve_local_list()
        return 0

    try:
        lock_handle = acquire_lock()
    except RuntimeError as exc:
        log(str(exc))
        return 2

    try:
        if args.refresh_unbound:
            refresh_unbound(force_fetch=True)
            log("DONE: NRD feed cache invalidated and Unbound DNSBL ingestion verified")
            return 0

        if args.clear:
            removed = clear_local_store()
            refresh_unbound(no_refresh=args.no_refresh, force_fetch=True)
            log(
                f"DONE: local NRD data cleared ({removed} daily archive(s)); "
                "Unbound DNSBL refresh requested"
            )
            return 0

        if args.rebuild:
            domains, valid_days, pruned, rebuilt = rebuild_local_store()
            if rebuilt:
                update_run_state(last_feed_rebuild_utc=utc_now_iso())
            if rebuilt or unbound_refresh_required():
                if not rebuilt:
                    log("Unbound ingestion is pending for the current feed; retrying refresh")
                refresh_unbound(no_refresh=args.no_refresh, force_fetch=True)
            else:
                log("Current NRD feed is already ingested by Unbound; skipping DNSBL refresh")
            log(f"DONE: {domains:,} unique NRD domains available from {valid_days} daily archive(s)")
            return 0

        domains, valid_days, pruned, rebuilt = update_local_store(no_backfill=args.no_backfill)
        if rebuilt:
            update_run_state(last_feed_rebuild_utc=utc_now_iso())
        if rebuilt or unbound_refresh_required():
            if not rebuilt:
                log("Unbound ingestion is pending for the current feed; retrying refresh")
            refresh_unbound(no_refresh=args.no_refresh, force_fetch=True)
        else:
            log("Feed unchanged and already ingested by Unbound; skipping DNSBL refresh")
        update_run_state(last_successful_update_utc=utc_now_iso())
        log(f"DONE: {domains:,} unique NRD domains available; {valid_days} daily archive(s) retained")
        return 0
    except Exception as exc:
        log(f"ERROR: {exc}")
        return 1
    finally:
        lock_handle.close()


if __name__ == "__main__":
    sys.exit(main())
