"""WhoisDS NRD downloader/rolling blocklist for OPNsense.

- Downloads the latest completed free WhoisDS daily NRD archives.
- Keeps a configurable number of daily archive files locally (1-15 days).
- Excludes configured TLD/suffixes from the published aggregate without
  modifying the downloaded daily source archives.
- Publishes each remaining apex domain and a wildcard entry for its subdomains.
- Serves that list on 127.0.0.1 only, for the Unbound DNSBL URL fetcher.
- Optionally invokes `configctl unbound dnsbl` after updating the list.

No third-party Python modules are required.
"""

