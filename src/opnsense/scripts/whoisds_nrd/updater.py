def parse_tld_exclusions(raw: str) -> set[str]:
    """Parse comma-separated DNS suffixes (for example: ru,cn,xyz).

    Leading dot or wildcard-dot notation is accepted for convenience. Multi-label
    suffixes such as co.uk are also supported. A malformed item is an error rather
    than silently disabling an operator's exclusion rule.
    """
    suffixes: set[str] = set()
    for item in (raw or "").split(","):
        value = item.strip().lower()
        if not value:
            continue
        if value.startswith("*."):
            value = value[2:]
        elif value.startswith("."):
            value = value[1:]
        value = value.rstrip(".")
        try:
            value = value.encode("idna").decode("ascii").lower()
        except UnicodeError as exc:
            raise ValueError(f"invalid TLD/suffix entry {item!r}") from exc
        labels = value.split(".")
        if not value or len(value) > 253 or any(
            not label or len(label) > 63 or not DOMAIN_LABEL_RE.fullmatch(label)
            for label in labels
        ):
            raise ValueError(
                f"invalid TLD/suffix entry {item!r}; use comma-separated values such as ru,cn,xyz"
            )
        suffixes.add(value)
    return suffixes


def load_settings() -> tuple[int, set[str]]:
    """Read settings generated by the OPNsense configd template.

    Missing settings use safe defaults so the service remains bootable before
    the GUI settings have ever been saved.
    """
    values: dict[str, str] = {}
    try:
        for line in SETTINGS_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    except FileNotFoundError:
        pass
    try:
        retention_days = int(values.get("RETENTION_DAYS", DEFAULT_RETENTION_DAYS))
    except ValueError as exc:
        raise ValueError("RETENTION_DAYS in generated settings is not an integer") from exc
    if not MIN_RETENTION_DAYS <= retention_days <= MAX_RETENTION_DAYS:
        raise ValueError(
            f"retention must be between {MIN_RETENTION_DAYS} and {MAX_RETENTION_DAYS} days"
        )
    exclusions = parse_tld_exclusions(values.get("EXCLUDED_TLDS", ""))
    return retention_days, exclusions


def domain_matches_excluded_suffix(domain: str, suffixes: set[str]) -> bool:
    """Match complete DNS label boundaries; never match a partial label."""
    return any(domain == suffix or domain.endswith("." + suffix) for suffix in suffixes)


def filter_excluded_tlds(domains: Iterable[str], suffixes: set[str]) -> tuple[set[str], int]:
    kept: set[str] = set()
    excluded = 0
    for domain in set(domains):
        if domain_matches_excluded_suffix(domain, suffixes):
            excluded += 1
        else:
            kept.add(domain)
    return kept, excluded


